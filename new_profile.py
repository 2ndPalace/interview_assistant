"""
新しい面接先のプロファイル（profiles/<id>.json）を作る。

使い方:
    python new_profile.py <id> <表示名> [--type baito|shinsotsu|intern]

例:
    python new_profile.py sample "サンプル商事（インターン）" --type intern

できたファイルの [要記入] を埋めれば、アプリの「面接先」から選べるようになる。
共通の質問（profiles/_common.json）は自動で読み込まれるので、ここには会社固有の質問だけを書く。
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

PROFILES_DIR = Path(__file__).resolve().parent / "profiles"


def q(qid, title, variants, keywords, points, full, sec):
    return {
        "id": qid,
        "title": title,
        "variants": variants,
        "keywords": keywords,
        "points": [{"text": t, "check": []} for t in points],
        "full": full,
        "target_seconds": sec,
    }


