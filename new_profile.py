def main():
    ap = argparse.ArgumentParser(description="新しい面接先のプロファイルを作る")
    ap.add_argument("id", help="ファイル名になる英数字（例: sample）")
    ap.add_argument("name", help="アプリに表示する名前（例: サンプル商事（インターン））")
    ap.add_argument("--type", choices=list(EXTRA), default="baito",
                    help="baito=アルバイト / shinsotsu=新卒採用 / intern=インターン（既定: baito）")
    ap.add_argument("--force", action="store_true", help="既にあるファイルを上書きする")
    args = ap.parse_args()

    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", args.id):
        sys.exit("id は英数字・ハイフン・アンダースコアで指定してください（先頭は英数字）")
    PROFILES_DIR.mkdir(exist_ok=True)
    path = PROFILES_DIR / f"{args.id}.json"
    if path.exists() and not args.force:
        sys.exit(f"{path.name} は既にあります。上書きする場合は --force を付けてください")

    doc = {
        "_説明": f"{args.name} の面接用。共通の質問(_common.json)に、この会社固有の質問を追加・上書きする。[要記入]を埋めること。",
        "name": args.name,
        "vocabulary": f"[要記入] 会社名・サービス名・業界用語を「、」区切りで（文字起こしの精度が上がる）",
        "questions": BASE + EXTRA[args.type],
    }
    path.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"作成しました: {path}")
    print("[要記入] を埋めてからアプリを起動し、「面接先」で選んでください。")


if __name__ == "__main__":
    main()
